export function buildDemoReply({ text, context, mode }, random = Math.random) {
    if (mode === 'solution') {
        const criteria = /срок|дат[аеуы]|очеред/i.test(text) ? 'срок и очередь' :
            /цен|бюджет|стоимост/i.test(text) ? 'бюджет и допустимое отклонение' : 'приоритет клиента и ограничения';
        return {text: `Для подбора по проекту «${context?.projectTitle || 'AIShtab'}» уточните ${criteria}. Что для клиента обязательно, а чем можно поступиться?\n\nВ демо нет каталога предложений для клиента. Я могу помочь сформулировать критерии, но не подтвердить доступность конкретного варианта.`, followUpQuestions:[]};
    }
    if (isPnLIncidentQuestion(text)) {
        return { text: buildPnLIncidentAnswer(), followUpQuestions: PNL_INCIDENT_FOLLOW_UP_QUESTIONS };
    }
    const index = Math.floor(random() * answerBuilders.length);
    return { text: answerBuilders[index](context), followUpQuestions: FOLLOW_UP_QUESTIONS[index] };
}

export async function requestDemoReply({ text, context, mode = 'assistant', signal }) {
    signal?.throwIfAborted();
    await new Promise((resolve, reject) => {
        const timer = setTimeout(() => {
            signal?.removeEventListener('abort', abort);
            resolve();
        }, responseDelay);
        function abort() {
            clearTimeout(timer);
            reject(signal.reason);
        }
        signal?.addEventListener('abort', abort, { once: true });
    });
    signal?.throwIfAborted();
    return buildDemoReply({ text, context, mode });
}
